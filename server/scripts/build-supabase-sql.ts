/**
 * Writes prisma/supabase/apply-migrations.sql: every migration in
 * prisma/migrations as one script you can paste into the Supabase SQL Editor.
 *
 * - Each migration runs only if `_prisma_migrations` doesn't already record it,
 *   so the file is safe to re-run and brings any database up to date.
 * - Applied migrations are recorded exactly as `prisma migrate deploy` would
 *   (same table, name and SHA-256 checksum), so both ways stay interchangeable.
 * - Everything runs in one transaction: on any error nothing is changed.
 *
 *   npm run db:sql            # regenerate after adding a migration
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const migrationsDir = join(root, "prisma", "migrations");
export const OUTPUT = join(root, "prisma", "supabase", "apply-migrations.sql");

export function buildSupabaseSql(): string {
  const migrations = readdirSync(migrationsDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

  const blocks = migrations.map((name) => {
    const sql = readFileSync(join(migrationsDir, name, "migration.sql"), "utf8");
    if (sql.includes("$migration_sql$")) throw new Error(`${name} contains the quoting tag $migration_sql$`);
    const checksum = createHash("sha256").update(sql).digest("hex");
    return `-- ${name}
DO $apply$
BEGIN
  IF EXISTS (SELECT 1 FROM "_prisma_migrations" WHERE "migration_name" = '${name}' AND "finished_at" IS NOT NULL AND "rolled_back_at" IS NULL) THEN
    RAISE NOTICE 'already applied: ${name}';
    RETURN;
  END IF;
  EXECUTE $migration_sql$
${sql.trimEnd()}
$migration_sql$;
  INSERT INTO "_prisma_migrations" ("id", "checksum", "migration_name", "started_at", "finished_at", "applied_steps_count")
  VALUES (gen_random_uuid()::text, '${checksum}', '${name}', now(), now(), 1);
  RAISE NOTICE 'applied: ${name}';
END
$apply$;
`;
  });

  return `-- =============================================================================
--  GENERATED by \`npm run db:sql\` from prisma/migrations. Do not edit by hand.
--
--  Paste this whole file into Supabase → SQL Editor → Run.
--  Safe to run again: migrations already recorded in _prisma_migrations are
--  skipped. It runs in a single transaction, so an error changes nothing.
-- =============================================================================

BEGIN;

-- Prisma's migration history table (same definition \`prisma migrate\` creates).
CREATE TABLE IF NOT EXISTS "_prisma_migrations" (
    "id"                  VARCHAR(36) PRIMARY KEY NOT NULL,
    "checksum"            VARCHAR(64) NOT NULL,
    "finished_at"         TIMESTAMPTZ,
    "migration_name"      VARCHAR(255) NOT NULL,
    "logs"                TEXT,
    "rolled_back_at"      TIMESTAMPTZ,
    "started_at"          TIMESTAMPTZ NOT NULL DEFAULT now(),
    "applied_steps_count" INTEGER NOT NULL DEFAULT 0
);

${blocks.join("\n")}
COMMIT;

-- Check: should list cell_groups, users, weekly_challenges, … with rls_enabled = true.
SELECT tablename, rowsecurity AS rls_enabled FROM pg_tables WHERE schemaname = 'public' ORDER BY tablename;
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(OUTPUT, buildSupabaseSql());
  console.log(`Wrote ${OUTPUT}`);
}
